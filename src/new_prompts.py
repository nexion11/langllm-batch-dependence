"""Write and review native prompts for the 12 new schemas in 7 languages.

The writer and reviewer instructions are LangLLM's (langllm/prompts.py and langllm/review.py,
commit 06109dc), reused so the new prompts follow the same protocol.

    python new_prompts.py write     # prompts/new/{lang}.json
    python new_prompts.py review    # prompts/new/review.csv
    python new_prompts.py fix       # rewrite flagged prompts with seeds 1-5, keep the first that passes

LangLLM fixed flagged prompts by hand. Here each flagged prompt is instead regenerated by the same writer
with the next seed and re-reviewed; every attempt is logged in prompts/new/fix_log.jsonl.
"""
import csv
import datetime as dt
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor

from study import AUDIENCE, LANGUAGES, PROMPT_REVIEWER, PROMPT_WRITER, PROMPTS, chat, schemas, text_of, usage_of

WRITER_SYSTEM = (
    "You write essay prompts for a research study. You write them the way a fluent, educated "
    "native speaker of the target language would write an assignment for another native speaker: "
    "natural phrasing, no translationese, no mention of any other language, no meta-commentary. "
    "Output ONLY the prompt text itself, nothing else."
)
WRITER_TEMPLATE = """Write an essay prompt in {name_en} ({native}).

The prompt must ask the reader to write a persuasive essay that:
- Topic: {topic}
- Position to argue: {stance_word} the proposition
- Must make exactly these three supporting points, in any order, each developed in its own paragraph:
  1. {c1}
  2. {c2}
  3. {c3}
- Written for {audience}
- Length: {length_hint}
- Prose only: continuous paragraphs. No headings, no bullet points, no numbered lists, no title, no tables.

Express all of this naturally in {name_en}, as a native speaker would phrase such an assignment. Do not translate this instruction literally; write the assignment fresh. Do not add any extra requirements. Output only the prompt."""
STANCE_WORD = {"for": "in favour of", "against": "against"}

EXTRACT = """Below is an essay assignment written in {name_en}. Read it and answer in English, as JSON only, with keys:
"topic": one sentence, what the essay is about;
"stance": "for" or "against" the proposition the essay must defend, or "unclear";
"points": list of every specific supporting point the assignment tells the writer to make (verbatim meaning, translated to English);
"prose_only": true if it forbids headings, bullet points or numbered lists, else false;
"length_stated": true if a length target is given, else false;
"native_quality": 1-5, where 5 = reads like a fluent native speaker wrote it, 1 = obvious translation or broken;
"other_language_mentioned": true if the text mentions any language or translation.

Assignment:
<<<
{prompt}
>>>"""
MATCH = """Compare an intended essay schema with what a reviewer extracted from the written prompt. Answer in JSON only:
"topic_match": true/false (same proposition, even if worded or scoped differently),
"stance_match": true/false — IMPORTANT: the intended stance is relative to the proposition "{topic}". "against" means the essay must argue AGAINST that proposition (e.g. against phasing out zoos = defending zoos). Judge whether the prompt asks for the same side of the proposition, not whether the word matches.
"subclaims_present": list of three booleans (was each intended sub-claim requested, same meaning),
"extra_claims": list of extracted points that are NOT among the intended sub-claims (empty if none),
"verdict": "pass" if topic and stance match, all three sub-claims present, no extra claims; else "fail",
"note": one short sentence.

Intended schema:
topic: {topic}
stance: {stance}
sub-claims: 1) {c1} 2) {c2} 3) {c3}

Extracted from the prompt:
{extracted}"""


def load(lang):
    p = PROMPTS / f"{lang}.json"
    return {d["id"]: d for d in json.loads(p.read_text(encoding="utf-8"))} if p.exists() else {}


def write_one(s, lang, seed=0):
    L = LANGUAGES[lang]
    user = WRITER_TEMPLATE.format(name_en=L["name_en"], native=L["native"], topic=s["topic"],
                                  stance_word=STANCE_WORD[s["stance"]], c1=s["subclaims"][0], c2=s["subclaims"][1],
                                  c3=s["subclaims"][2], audience=AUDIENCE[s["fk_tier"]], length_hint=L["length_hint"])
    resp = chat(PROMPT_WRITER, [{"role": "system", "content": WRITER_SYSTEM}, {"role": "user", "content": user}],
                temperature=0.4, max_tokens=900, seed=seed)
    return {"id": s["id"], "lang": lang, "prompt": text_of(resp), "schema": s, "writer_model": PROMPT_WRITER,
            "writer_model_served": resp.get("model"), "writer_seed": seed, "usage": usage_of(resp),
            "written_at": dt.datetime.now(dt.timezone.utc).isoformat()}


def save(lang, prompts):
    (PROMPTS / f"{lang}.json").write_text(json.dumps(sorted(prompts.values(), key=lambda d: d["id"]),
                                                     ensure_ascii=False, indent=2), encoding="utf-8")


def fix(max_seed=5):
    rows = list(csv.DictReader(open(PROMPTS / "review.csv", encoding="utf-8")))
    by = {s["id"]: s for s in schemas()}

    def one(r):
        for seed in range(1, max_seed + 1):
            cand = write_one(by[r["id"]], r["lang"], seed)
            rev = review_one(by[r["id"]], cand, r["lang"])
            with open(PROMPTS / "fix_log.jsonl", "a", encoding="utf-8") as f:
                f.write(json.dumps({**rev, "seed": seed, "prompt": cand["prompt"], "usage": cand["usage"]},
                                   ensure_ascii=False) + "\n")
            if rev["verdict"] == "pass":
                return r, cand, rev
        return r, None, rev

    with ThreadPoolExecutor(max_workers=6) as ex:
        results = list(ex.map(one, [r for r in rows if r["verdict"] != "pass"]))
    for r, cand, rev in results:
        if cand:
            prompts = load(r["lang"])
            prompts[r["id"]] = cand
            save(r["lang"], prompts)
            r.update(verdict="pass", flags="", native_quality=rev["native_quality"], note=f"fixed at seed {cand['writer_seed']}")
        else:
            r["note"] = "still flagged after seeds 1-%d: %s" % (max_seed, rev["flags"])
    with open(PROMPTS / "review.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"{sum(r['verdict'] == 'pass' for r in rows)}/{len(rows)} prompts pass after fixing")


def write(langs, force=False):
    PROMPTS.mkdir(parents=True, exist_ok=True)
    for lang in langs:
        have = {} if force else load(lang)
        L = LANGUAGES[lang]
        for s in schemas():
            if s["id"] in have:
                continue
            user = WRITER_TEMPLATE.format(name_en=L["name_en"], native=L["native"], topic=s["topic"],
                                          stance_word=STANCE_WORD[s["stance"]], c1=s["subclaims"][0], c2=s["subclaims"][1],
                                          c3=s["subclaims"][2], audience=AUDIENCE[s["fk_tier"]], length_hint=L["length_hint"])
            resp = chat(PROMPT_WRITER, [{"role": "system", "content": WRITER_SYSTEM}, {"role": "user", "content": user}],
                        temperature=0.4, max_tokens=900, seed=0)
            have[s["id"]] = {"id": s["id"], "lang": lang, "prompt": text_of(resp), "schema": s,
                             "writer_model": PROMPT_WRITER, "writer_model_served": resp.get("model"),
                             "usage": usage_of(resp), "written_at": dt.datetime.now(dt.timezone.utc).isoformat()}
            print(f"[{lang}] {s['id']} written ({len(have[s['id']]['prompt'])} chars)", flush=True)
        (PROMPTS / f"{lang}.json").write_text(json.dumps(sorted(have.values(), key=lambda d: d["id"]),
                                                         ensure_ascii=False, indent=2), encoding="utf-8")


def _json(text):
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip(), flags=re.M)
    i = text.find("{")
    try:
        return json.JSONDecoder().raw_decode(text[i:])[0] if i >= 0 else {"_parse_error": text[:300]}
    except json.JSONDecodeError:
        return {"_parse_error": text[:300]}


def review_one(s, p, lang):
    ask = lambda content, n: _json(text_of(chat(PROMPT_REVIEWER, [{"role": "user", "content": content}], temperature=0.0,
                                                 max_tokens=n, seed=0, reasoning={"enabled": False})))
    ex = ask(EXTRACT.format(name_en=LANGUAGES[lang]["name_en"], prompt=p["prompt"]), 900)
    mt = ask(MATCH.format(topic=s["topic"], stance=s["stance"], c1=s["subclaims"][0], c2=s["subclaims"][1],
                          c3=s["subclaims"][2], extracted=json.dumps(ex, ensure_ascii=False)), 600)
    flags = [f for f, bad in (("content", mt.get("verdict") != "pass"), ("no_prose_only", not ex.get("prose_only")),
                              ("no_length", not ex.get("length_stated")), ("non_native", (ex.get("native_quality") or 0) < 4),
                              ("mentions_language", bool(ex.get("other_language_mentioned"))),
                              ("parse_error", "_parse_error" in ex or "_parse_error" in mt)) if bad]
    print(f"[{lang}] {s['id']}: {'pass' if not flags else 'flag ' + ','.join(flags)}", flush=True)
    return {"id": s["id"], "lang": lang, "verdict": "pass" if not flags else "flag", "flags": ";".join(flags),
            "native_quality": ex.get("native_quality"), "note": mt.get("note", "")}


def review(langs):
    jobs = [(s, load(lang)[s["id"]], lang) for lang in langs for s in schemas()]
    with ThreadPoolExecutor(max_workers=6) as ex:
        rows = list(ex.map(lambda j: review_one(*j), jobs))
    with open(PROMPTS / "review.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"{sum(r['verdict'] == 'pass' for r in rows)}/{len(rows)} prompts pass")


if __name__ == "__main__":
    cmd, langs = sys.argv[1], sys.argv[2:] or list(LANGUAGES)
    if cmd == "fix":
        fix()
    elif cmd == "write":
        write(langs, force="--force" in langs)
    else:
        review([l for l in langs if l != "--force"])
